"""build_master.py - assembles MASTER_DESIGN.md from design_src/*.md and the generated tables.
Run tools/design_data.py first if any number changed."""
import os, re, datetime
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); SRC = os.path.join(ROOT, "design_src")
ORDER = ["01_research", "02_vision", "03_gdd", "04_05_art", "06_audio", "07_technical", "08_vm_build", "09_assets", "10_qa", "11_production", "12_handoff"]
def include(m):
    p = os.path.join(SRC, "_tables", m.group(1) + ".md")
    if not os.path.exists(p): raise SystemExit(f"missing table {m.group(1)}")
    return open(p).read().strip()
body = []
for name in ORDER:
    t = open(os.path.join(SRC, name + ".md")).read().strip()
    t = re.sub(r"\{\{TABLE:([a-z_]+)\}\}", include, t)
    body.append(t)
text = "\n\n---\n\n".join(body)
if "{{TABLE:" in text: raise SystemExit("unresolved table placeholder")
toc = []
for line in text.splitlines():
    m = re.match(r"^(#{1,2}) (.+)$", line)
    if m and not line.startswith("###"):
        title = m.group(2).strip(); anchor = re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")
        toc.append(("" if m.group(1) == "#" else "  ") + f"- [{title}](#{anchor})")
head = f"""# BRIC-A-BRAWL: master design document

Pre-production package for a browser party fighter. Working title was "Fracture".
Generated from `design_src/` by `tools/build_master.py`. Do not edit this file; edit the chapter and rebuild.
Numbers come from `tools/design_data.py` and are also in `data/*.json`.

Read `00_READ_THIS_FIRST.md` before this. The art bible (chapter 4) is `ART_BIBLE.md`; the concept art critique (chapter 5) is `concept_art/CRITIQUE.md`.

## Contents

""" + "\n".join(toc) + "\n\n---\n\n"
open(os.path.join(ROOT, "MASTER_DESIGN.md"), "w").write(head + text + "\n")
words = len(re.findall(r"\w+", text))
print(f"MASTER_DESIGN.md written: {len(text.splitlines())} lines, about {words} words, {len(toc)} contents entries")
